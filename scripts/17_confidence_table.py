#!/usr/bin/env python3
"""
Per-case AF3 confidence: pLDDT (fold quality) and iPTM (interface-pose quality).

The two are not interchangeable.
  pLDDT is per-residue confidence in the local fold. It is the number that matters
  for WALLE, which is pose-independent: it reads the antibody and the antigen as
  two separate graphs and never sees inter-chain geometry, so a mis-docked
  antibody cannot hurt it but a badly folded antigen can.
  iPTM is confidence in the interface pose. It is the number that matters for
  AF3's own contact-based epitope prediction, and it is irrelevant to WALLE.
Reporting one in place of the other is the easiest way to reach a wrong conclusion
about whether a failure is input-limited or a genuine model failure.

The top-ranked model is used throughout, matching the headline scoring convention
(AF3 = contact_top, so AF3, WALLE and ESMFold2 are all read off one structure).
AF3 writes per-atom pLDDT into the mmCIF B-factor column.

Output: results/confidence_per_case.csv
    case_id, task, iptm, ptm, ranking_score, plddt_antigen, plddt_ab, plddt_all

    PYTHONPATH=scripts python scripts/17_confidence_table.py
"""
import glob
import sys
import json
from pathlib import Path

import numpy as np
import pandas as pd

PROJECT = Path(__file__).resolve().parents[1]
OUT = PROJECT / "results" / "confidence_per_case.csv"

# (task tag, AF3 output root). The antigen is chain A in every task; the antibody
# is H (+L on Task II, which folds an Fv).
DATASETS = [("task2", "work/af3_out"),
            ("task3", "work/task3/af3_out"),
            ("task3cov", "work/task3cov/af3_out")]
ANTIGEN_CHAIN = "A"


def top_model(case_dir: Path):
    """AF3 writes its own top-ranked model as <case>/<case>_model.cif.

    Verified elsewhere that its coordinates are identical to the sample with the
    highest ranking_score, so this needs no re-ranking of our own.
    """
    c = case_dir / f"{case_dir.name}_model.cif"
    if c.exists():
        return c
    f = sorted(case_dir.glob("*_model.cif"))
    return f[0] if f else None


def per_chain_plddt(cif):
    import gemmi
    st = gemmi.read_structure(str(cif))
    st.setup_entities()
    out = {}
    for ch in st[0]:
        if not len(ch):
            continue
        out[ch.name] = np.array([np.mean([a.b_iso for a in r]) for r in ch])
    return out


def confidences(case_dir: Path):
    f = sorted(case_dir.glob("*summary_confidences.json"))
    if not f:
        return {}
    d = json.load(open(f[0]))
    return {k: d.get(k) for k in ("iptm", "ptm", "ranking_score", "fraction_disordered",
                                  "has_clash")}


def main():
    rows = []
    for task, root in DATASETS:
        base = PROJECT / root
        if not base.exists():
            print(f"  {task}: {base} absent, skipped")
            continue
        dirs = sorted(p for p in base.iterdir() if p.is_dir())
        print(f"  {task}: {len(dirs)} cases")
        for k, cd in enumerate(dirs):
            cif = top_model(cd)
            r = {"case_id": cd.name, "task": task}
            r.update(confidences(cd))
            if cif is not None:
                try:
                    pc = per_chain_plddt(cif)
                except Exception as e:                      # a truncated cif, not fatal
                    print(f"    {cd.name}: {e}")
                    pc = {}
                if pc:
                    ag = pc.get(ANTIGEN_CHAIN)
                    ab = [v for c, v in pc.items() if c != ANTIGEN_CHAIN]
                    allv = np.concatenate(list(pc.values()))
                    r["plddt_antigen"] = float(np.mean(ag)) if ag is not None else np.nan
                    r["plddt_ab"] = float(np.mean(np.concatenate(ab))) if ab else np.nan
                    r["plddt_all"] = float(np.mean(allv))
                    r["n_res_antigen"] = int(len(ag)) if ag is not None else 0
            rows.append(r)
            if (k + 1) % 100 == 0:
                print(f"    {k + 1}/{len(dirs)}")
    d = pd.DataFrame(rows)
    if d.empty:
        sys.exit("no AlphaFold3 output found under " +
                 ", ".join(str(PROJECT / r) for _, r in DATASETS) +
                 ". These are the predicted structures, which are regenerated by "
                 "the folding stages rather than shipped.")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    d.to_csv(OUT, index=False)
    print(f"\n{len(d)} rows -> {OUT}")
    for t, g in d.groupby("task"):
        print(f"  {t:10s} iptm {g.iptm.mean():.3f}  "
              f"plddt_antigen {g.plddt_antigen.mean():.1f}  "
              f"(missing: iptm {g.iptm.isna().sum()}, plddt {g.plddt_antigen.isna().sum()})")


if __name__ == "__main__":
    main()
